class ClassName:
    def method_name(self, parameter1, parameter2):
        return parameter1 + parameter2  # Ví dụ: cộng hai giá trị

# Gán giá trị cho value1 và value2
value1 = 5
value2 = 10

# Tạo đối tượng và gọi phương thức
object_name = ClassName()
result = object_name.method_name(value1, value2)
print(result)  # Kết quả là 15
